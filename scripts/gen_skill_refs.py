"""Regenerates the reference files bundled with the PyBroker agent skills.

Rebuilds, deterministically from local sources, for each skill listed in
``SKILLS`` (under ``skills/<name>/references/``):

- ``wiki-*.md`` mirrors of the documentation notebooks in
  ``docs/source/notebooks/`` — every notebook for full-wiki skills, or
  only the wiki files a subset skill already bundles.
- ``api-public-surface.md`` from the public signatures and docstrings in
  ``src/pybroker/`` (identical content for every skill bundling it).
- ``pybroker_*.pyi`` type-stub references from the classes and functions
  registered in ``STUBS`` (identical content for every skill bundling
  them). The stubs are reference documents for coding agents — valid
  ``.pyi`` syntax, but never installed or packaged. Verify them by hand
  with ``mypy --ignore-missing-imports pybroker_*.pyi`` (from a venv on
  the tooling Python) from inside a skill's ``references/`` directory.
- The "User Guide Wiki" entry block of ``wiki-index.md``, for skills
  whose index is generator-owned.

Run with a project venv on the tooling Python (3.12, see
``.github/python-versions.json``) so output is stable across machines
(``ast.unparse`` formatting differs between Python versions)::

    <venv>/bin/python scripts/gen_skill_refs.py
    ruff format skills/*/references/*.pyi
    <venv>/bin/python scripts/gen_skill_refs.py --check

``--check`` rebuilds everything in memory and exits non-zero if any
generated file on disk differs, without writing. This module does not
invoke ruff itself: the raw ``ast.unparse`` output for the ``.pyi`` stubs
uses single quotes and omits blank lines after class docstrings, which
disagrees with the project's ruff style, so a ``ruff format`` pass over
the generated stubs is required before ``--check`` (or a commit) will
pass cleanly.
"""

